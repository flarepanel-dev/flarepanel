/**
 * One-off generator for the Realtime preview's world map. It draws the same
 * Natural Earth 110m countries the dashboard's Realtime page uses, in the same
 * Mercator band (84°N to 58°S, Antarctica hidden), into a static SVG, and
 * projects the sample cities to percentages of that box.
 *
 *   bun scripts/build-map.ts   (from apps/landing; uses apps/start's map deps)
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { geoMercator, geoPath } from '../../start/node_modules/d3-geo';
import { feature, mesh } from '../../start/node_modules/topojson-client';
import atlas from '../../start/node_modules/world-atlas/countries-110m.json';

const W = 1000;
const NORTH = 84;
const SOUTH = -58;

const topology = atlas as never;
const countries = feature(topology, (atlas as any).objects.countries) as any;
countries.features = countries.features.filter(
  (f: any) => f.properties.name !== 'Antarctica'
);

const projection = geoMercator().scale(1).translate([0, 0]);
const [, yN] = projection([0, NORTH]) as [number, number];
const [, yS] = projection([0, SOUTH]) as [number, number];
const [xW] = projection([-180, 0]) as [number, number];
const [xE] = projection([180, 0]) as [number, number];
const k = W / (xE - xW);
projection.scale(k).translate([-xW * k, -yN * k]);
const H = Math.round((yS - yN) * k);

const path = geoPath(projection).digits(0);
const land = path(countries) ?? '';
const borders =
  path(
    mesh(topology, (atlas as any).objects.countries, (a: any, b: any) => a !== b)
  ) ?? '';

// Countries drawn once; the stroke in the page colour draws the borders.
void borders;
const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" preserveAspectRatio="xMidYMid slice"><path d="${land}" fill="#2a2a2a" stroke="#161616" stroke-width="0.8" stroke-linejoin="round"/></svg>`;
writeFileSync(join(import.meta.dir, '..', 'public', 'realtime-map.svg'), svg);

const CITIES: Record<string, [number, number]> = {
  'San Francisco': [-122.42, 37.77],
  'New York': [-74.0, 40.71],
  Toronto: [-79.38, 43.65],
  'São Paulo': [-46.63, -23.55],
  London: [-0.13, 51.51],
  Lisbon: [-9.14, 38.72],
  Berlin: [13.4, 52.52],
  Stockholm: [18.07, 59.33],
  Istanbul: [28.98, 41.01],
  Lagos: [3.38, 6.52],
  Bengaluru: [77.59, 12.97],
  Singapore: [103.82, 1.35],
  Tokyo: [139.69, 35.68],
  Sydney: [151.21, -33.87],
};
const positions = Object.fromEntries(
  Object.entries(CITIES).map(([name, lonLat]) => {
    const [x, y] = projection(lonLat) as [number, number];
    return [name, [+((x / W) * 100).toFixed(2), +((y / H) * 100).toFixed(2)]];
  })
);
writeFileSync(
  join(import.meta.dir, '..', 'src', 'components', 'product', 'map-positions.ts'),
  `// Generated by scripts/build-map.ts: city positions as % of public/realtime-map.svg.\nexport const MAP_RATIO = ${(W / H).toFixed(4)};\nexport const CITY_POSITIONS: Record<string, [number, number]> = ${JSON.stringify(positions, null, 2)};\n`
);
console.log(`map ${W}x${H}, ${(svg.length / 1024).toFixed(1)} KB`);
